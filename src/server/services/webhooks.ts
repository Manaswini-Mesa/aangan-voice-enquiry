export interface WebhookOutcome {
  status: "processed" | "duplicate" | "ignored" | "failed";
  eventType: string;
  pendingNotifications: string[];
  callId?: string;
}

const LIVE_KEY = (id: string): CallKey => ({ provider: "vaani", providerCallId: id, mode: "live" });

/** Records a voice-minute usage event. VaaniVoice publishes no usage/billing API, so cost is an estimate or unavailable. */
async function recordVoiceUsage(db: Db, call: CallRow, durationSec: number) {
  const perMin = config().vaani.inrPerMinuteEstimate;
  const minutes = Math.round((durationSec / 60) * 100) / 100;
  await db.query(
    `INSERT INTO usage_events (lead_id, call_id, provider, kind, quantity, unit, cost_amount, cost_currency, cost_type, mode, metadata, idempotency_key)
     VALUES ($1,$2,'vaani','voice_minutes',$3,'minutes',$4,$5,$6,$7,$8,$9) ON CONFLICT (idempotency_key) DO NOTHING`,
    [
      call.lead_id,
      call.id,
      minutes,
      perMin !== undefined ? Math.round(minutes * perMin * 100) / 100 : null,
      perMin !== undefined ? "INR" : null,
      perMin !== undefined ? "estimate" : "unavailable",
      call.mode,
      JSON.stringify({ source: "call_ended webhook duration" }),
      `voice:${call.id}`,
    ],
  );
}

/** Runs the provider transcript's caller lines through the engine when we did not drive the call (no BYOL turns). */
export async function replayTranscript(tx: Db, call: CallRow, transcript: string) {
  const lines = parseVaaniTranscript(transcript);
  let state = call.conversation_state as ConversationState;
  if (state.turn > 0 || !lines.some((l) => l.speaker === "caller")) return false;
  const rules = config().rules;
  const now = new Date(call.started_at);
  let seq = 1;
  for (const line of lines) {
    await tx.query(`INSERT INTO transcript_segments (call_id, seq, speaker, text) VALUES ($1,$2,$3,$4) ON CONFLICT (call_id, seq) DO NOTHING`, [call.id, seq++, line.speaker, line.text]);
    if (line.speaker === "caller") {
      const out = processTurn({ ...state, ended: false }, { text: line.text, now }, { rules });
      state = out.state;
    } else if (guardOutbound(line.text).blocked) {
      // The provider's own LLM spoke this line; our guard can't block it after the fact, so flag it.
      await opsEvent(tx, "error", "pricing_guard", "PROVIDER_AGENT_PRICE_DISCLOSURE", "The VaaniVoice agent appears to have stated a price, range or rate on a call. Review the transcript and tighten the agent prompt.", call.lead_id, { callId: call.id });
    }
  }
  state = disconnect({ ...state, ended: false }, rules, "completed").state;
  await tx.query(`UPDATE calls SET conversation_state = $2 WHERE id = $1`, [call.id, JSON.stringify(state)]);
  await opsEvent(tx, "info", "voice", "POSTCALL_REPLAY", "Qualified from the provider transcript (agent replies were not generated by this system).", call.lead_id, { callId: call.id });
  return true;
}

export async function processVaaniWebhook(db: Db, payload: unknown): Promise<WebhookOutcome> {
  const e: NormalizedVoiceEvent = normalizeVaaniWebhook(payload);
  const key = webhookEventKey(e, payload);
  const inserted = await db.query<{ id: string }>(
    `INSERT INTO webhook_events (provider, event_type, event_key, provider_call_id, payload) VALUES ('vaani',$1,$2,$3,$4)
     ON CONFLICT (event_key) DO NOTHING RETURNING id`,
    [e.rawType, key, e.providerCallId ?? null, JSON.stringify(redactPayload(payload))],
  );
  if (!inserted[0]) return { status: "duplicate", eventType: e.rawType, pendingNotifications: [] };
  const eventId = inserted[0].id;
  const mark = (status: string, error?: string) =>
    db.query(`UPDATE webhook_events SET status = $2, error = $3, processed_at = now() WHERE id = $1`, [eventId, status, error ?? null]);

  try {
    if (!e.providerCallId) {
      await mark("ignored", "No call identifier in payload");
      return { status: "ignored", eventType: e.rawType, pendingNotifications: [] };
    }
    // Malformed or missing provider timestamps fall back to the time we received the event.
    const parsedAt = e.timestamp ? new Date(e.timestamp) : null;
    const at = parsedAt && !Number.isNaN(parsedAt.getTime()) ? parsedAt : new Date();
    let pending: string[] = [];
    let callId: string | undefined;
    switch (e.type) {
      case "call_started":
      case "call_answered": {
        const r = await ensureCall(db, LIVE_KEY(e.providerCallId), { callerNumber: e.phoneNumber, at });
        callId = r.call.id;
        break;
      }
      case "call_ended": {
        const existing = await db.query<CallRow>(`SELECT * FROM calls WHERE provider = 'vaani' AND provider_call_id = $1`, [e.providerCallId]);
        if (!existing[0]) {
          await ensureCall(db, LIVE_KEY(e.providerCallId), { at });
        }
        const call = (await db.query<CallRow>(`SELECT * FROM calls WHERE provider = 'vaani' AND provider_call_id = $1`, [e.providerCallId]))[0];
        const state = call.conversation_state as ConversationState;
        if (e.durationSec !== undefined) await recordVoiceUsage(db, call, e.durationSec);
        if (state.turn === 0) {
          // We did not drive this call (BYOL not used or fell back). Wait for call_postprocessing
          // to qualify from the transcript; the sweep finalizes it if that never arrives.
          await db.query(`UPDATE calls SET status = 'completed', ended_at = COALESCE(ended_at,$2), end_reason = $3, duration_sec = COALESCE($4, duration_sec) WHERE id = $1`, [
            call.id,
            at.toISOString(),
            e.endReason ?? "ended",
            e.durationSec ?? null,
          ]);
        } else {
          const r = await endCall(db, LIVE_KEY(e.providerCallId), { reason: e.endReason, durationSec: e.durationSec, at });
          pending = r.pendingNotifications;
        }
        callId = call.id;
        break;
      }
      case "call_postprocessing": {
        const r = await db.tx(async (tx) => {
          let call = (await tx.query<CallRow>(`SELECT * FROM calls WHERE provider = 'vaani' AND provider_call_id = $1`, [e.providerCallId]))[0];
          if (!call) {
            await ensureCall(tx, LIVE_KEY(e.providerCallId!), { at });
            call = (await tx.query<CallRow>(`SELECT * FROM calls WHERE provider = 'vaani' AND provider_call_id = $1`, [e.providerCallId]))[0];
          }
          await tx.query(
            `UPDATE calls SET provider_summary = $2, provider_transcript = $3, recording_available = $4, recording_ref = $5,
               duration_sec = COALESCE(duration_sec, $6) WHERE id = $1`,
            [
              call.id,
              e.summary ?? null,
              e.transcript ?? null,
              !!e.recordingUrl && config().recordingEnabled,
              config().recordingEnabled ? e.recordingUrl ?? null : null,
              e.durationSec ?? null,
            ],
          );
          let p: string[] = [];
          if (e.transcript && (await replayTranscript(tx, call, e.transcript))) {
            p = await finalizeInTx(tx, call.id);
          } else if (!call.finalized_at && call.status !== "active") {
            p = await finalizeInTx(tx, call.id);
          }
          return { pending: p, callId: call.id };
        });
        pending = r.pending;
        callId = r.callId;
        break;
      }
      case "transfer_initiated":
      case "transfer_succeeded":
      case "transfer_failed": {
        const call = (await db.query<CallRow>(`SELECT * FROM calls WHERE provider = 'vaani' AND provider_call_id = $1`, [e.providerCallId]))[0];
        if (call) {
          await audit(db, { label: "vaani" }, `call.${e.type}`, "call", call.id, call.lead_id, undefined, { reason: e.endReason });
          if (e.type === "transfer_failed") await opsEvent(db, "warn", "voice", "TRANSFER_FAILED", `Warm transfer failed (${e.endReason ?? "unknown"}).`, call.lead_id);
          callId = call.id;
        }
        break;
      }
      case "call_failed":
        await opsEvent(db, "error", "voice", "CALL_FAILED", `Provider reported call failure (${e.endReason ?? "unknown"}).`);
        break;
      default:
        await mark("ignored", "Unhandled event type");
        return { status: "ignored", eventType: e.rawType, pendingNotifications: [] };
    }
    await mark("processed");
    return { status: "processed", eventType: e.rawType, pendingNotifications: pending, callId };
  } catch (err) {
    await mark("failed", (err as Error).message.slice(0, 300));
    await opsEvent(db, "error", "webhook", "WEBHOOK_PROCESSING_FAILED", `Vaani ${e.rawType} webhook failed: ${(err as Error).message.slice(0, 200)}`);
    return { status: "failed", eventType: e.rawType, pendingNotifications: [] };
  }
}

/** Stored webhook payloads keep structure but drop recording URLs unless recording is enabled. */
function redactPayload(payload: unknown): unknown {
  if (!payload || typeof payload !== "object") return payload;
  const copy = JSON.parse(JSON.stringify(payload)) as Record<string, unknown>;
  if (!config().recordingEnabled) {
    if (copy.data && typeof copy.data === "object") delete (copy.data as Record<string, unknown>).recording_url;
    delete copy.recording_url;
  }
  return copy;
}

/**
 * Retention: once a lead passes retention_until (TRANSCRIPT_RETENTION_DAYS after first contact),
 * its transcripts, provider transcript copies and recording references are removed. The lead,
 * its facts and its qualification/audit history remain for reporting.
 */
export async function applyRetention(db: Db): Promise<number> {
  const expired = await db.query<{ id: string }>(
    `SELECT c.id FROM calls c JOIN leads l ON l.id = c.lead_id
     WHERE l.retention_until IS NOT NULL AND l.retention_until < now()
       AND (c.provider_transcript IS NOT NULL OR c.recording_ref IS NOT NULL
            OR EXISTS (SELECT 1 FROM transcript_segments s WHERE s.call_id = c.id))`,
  );
  for (const c of expired) {
    await db.tx(async (tx) => {
      await tx.query(`DELETE FROM transcript_segments WHERE call_id = $1`, [c.id]);
      await tx.query(`UPDATE calls SET provider_transcript = NULL, recording_ref = NULL, recording_available = false WHERE id = $1`, [c.id]);
    });
  }
  if (expired.length) await opsEvent(db, "info", "retention", "TRANSCRIPTS_PURGED", `Removed transcripts/recording references for ${expired.length} call(s) past retention.`);
  return expired.length;
}

/** Sweep: finalize calls that ended without finalization (e.g. post-processing never arrived). */
export async function finalizeStaleCalls(db: Db): Promise<{ finalized: number; pending: string[] }> {
  const stale = await db.query<{ id: string }>(
    `SELECT id FROM calls WHERE finalized_at IS NULL AND (
       (status <> 'active' AND ended_at < now() - interval '15 minutes') OR
       (status = 'active' AND started_at < now() - interval '2 hours'))`,
  );
  const pending: string[] = [];
  for (const c of stale) {
    const ids = await db.tx(async (tx) => {
      await tx.query(`UPDATE calls SET status = CASE WHEN status = 'active' THEN 'disconnected' ELSE status END, ended_at = COALESCE(ended_at, now()) WHERE id = $1`, [c.id]);
      const call = (await tx.query<CallRow>(`SELECT * FROM calls WHERE id = $1`, [c.id]))[0];
      const st = call.conversation_state as ConversationState;
      if (!st.ended) await tx.query(`UPDATE calls SET conversation_state = $2 WHERE id = $1`, [c.id, JSON.stringify(disconnect(st, config().rules).state)]);
      return finalizeInTx(tx, c.id);
    });
    pending.push(...ids);
  }
  if (stale.length) await opsEvent(db, "warn", "sweep", "STALE_CALLS_FINALIZED", `Finalized ${stale.length} call(s) that ended without completion.`);
  await audit(db, SYSTEM_ACTOR, "sweep.run", "system", "sweep", null, undefined, { finalized: stale.length });
  return { finalized: stale.length, pending };
}
